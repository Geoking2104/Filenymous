//! Agent Vault — integrity zome.
//!
//! Doppler-style "secrets for AI agents" on Holochain: an owner issues an AI
//! agent a scoped, read-only, expiring token (a capability grant) that lets it
//! fetch one sealed bundle of environment variables. Every issue / fetch /
//! denial / revocation / rotation is an append-only `AccessEvent` on the
//! owner's source chain.
//!
//! All entry types are **private** (never published to the DHT) and the zome
//! defines **no link types**: links are always public in Holochain and would
//! leak metadata. Lookups use `query()` on the local chain instead.
//!
//! The conductor never sees plaintext: `SealedBundle.ciphertext` is sealed in
//! the owner's browser vault to the agent's X25519 key.

use hdi::prelude::*;

pub mod policy;
pub mod rules;

pub use policy::*;
pub use rules::*;

/// A named scope (Doppler "branch config"): which vault items are exposed to an
/// agent, and under which env var names. The mapping is encrypted under the
/// owner's vault key (opaque to the conductor).
#[hdk_entry_helper]
#[derive(Clone, PartialEq)]
pub struct AgentConfig {
    pub config_id: String,
    pub name: String,
    #[serde(with = "serde_bytes")]
    pub enc_manifest: Vec<u8>,
    pub created_at: Timestamp,
}

/// Doppler "service token": metadata of one capability grant issued to one agent key.
#[hdk_entry_helper]
#[derive(Clone, PartialEq)]
pub struct AgentToken {
    pub token_id: String,
    pub config_id: String,
    pub label: String,
    /// Grantee: Ed25519 zome-call signing key generated by the agent runner.
    pub agent_key: AgentPubKey,
    /// Agent X25519 public key the bundle is sealed to (32 bytes).
    #[serde(with = "serde_bytes")]
    pub agent_x25519: Vec<u8>,
    /// Action hash of the `CapGrant` this token is backed by.
    pub grant_action_hash: ActionHash,
    pub issued_at: Timestamp,
    pub expires_at: Timestamp,
    /// 0 = unlimited within the TTL.
    pub max_uses: u32,
}

/// Env map sealed to one agent (one token). New versions are appended on rotation.
#[hdk_entry_helper]
#[derive(Clone, PartialEq)]
pub struct SealedBundle {
    pub token_id: String,
    pub version: u32,
    pub alg: String,
    #[serde(with = "serde_bytes")]
    pub eph_pub: Vec<u8>,
    #[serde(with = "serde_bytes")]
    pub nonce: Vec<u8>,
    #[serde(with = "serde_bytes")]
    pub ciphertext: Vec<u8>,
    pub created_at: Timestamp,
}

#[hdk_entry_helper]
#[derive(Clone, PartialEq)]
pub struct TokenRevocation {
    pub token_id: String,
    pub reason: String,
    pub revoked_at: Timestamp,
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
#[serde(tag = "type", content = "reason")]
pub enum AccessKind {
    Issued,
    Fetch,
    Denied(String),
    Revoked,
    Rotated,
}

/// Append-only audit record.
#[hdk_entry_helper]
#[derive(Clone, PartialEq)]
pub struct AccessEvent {
    pub token_id: String,
    pub kind: AccessKind,
    /// Who made the call (agent signing key for fetches, owner for admin actions).
    pub provenance: AgentPubKey,
    pub bundle_version: Option<u32>,
    pub at: Timestamp,
}

#[hdk_entry_types]
#[unit_enum(UnitEntryTypes)]
pub enum EntryTypes {
    #[entry_type(visibility = "private")]
    AgentConfig(AgentConfig),
    #[entry_type(visibility = "private")]
    AgentToken(AgentToken),
    #[entry_type(visibility = "private")]
    SealedBundle(SealedBundle),
    #[entry_type(visibility = "private")]
    TokenRevocation(TokenRevocation),
    #[entry_type(visibility = "private")]
    AccessEvent(AccessEvent),
}

#[hdk_extern]
pub fn validate(op: Op) -> ExternResult<ValidateCallbackResult> {
    match op.flattened::<EntryTypes, ()>()? {
        // Author-side validation (the entry is present): full content checks.
        FlatOp::StoreRecord(OpRecord::CreateEntry { app_entry, action }) => Ok(to_callback(
            validate_create(&app_entry, &action.author, action.timestamp),
        )),
        FlatOp::StoreEntry(OpEntry::CreateEntry { app_entry, action }) => Ok(to_callback(
            validate_create(&app_entry, &action.author, action.timestamp),
        )),
        // DHT validators only see the action of a private entry: nothing to check.
        FlatOp::StoreRecord(OpRecord::CreatePrivateEntry { .. }) => {
            Ok(ValidateCallbackResult::Valid)
        }

        // Append-only: no app entry of this DNA may ever be updated.
        FlatOp::StoreRecord(OpRecord::UpdateEntry { .. })
        | FlatOp::StoreRecord(OpRecord::UpdatePrivateEntry { .. })
        | FlatOp::StoreEntry(OpEntry::UpdateEntry { .. })
        | FlatOp::RegisterAgentActivity(OpActivity::UpdateEntry { .. })
        | FlatOp::RegisterAgentActivity(OpActivity::UpdatePrivateEntry { .. }) => {
            Ok(ValidateCallbackResult::Invalid(APPEND_ONLY.into()))
        }
        FlatOp::RegisterUpdate(OpUpdate::Entry { .. })
        | FlatOp::RegisterUpdate(OpUpdate::PrivateEntry { .. }) => {
            Ok(ValidateCallbackResult::Invalid(APPEND_ONLY.into()))
        }

        // Deletes: allowed for system entries (revoking a CapGrant), forbidden for app entries.
        FlatOp::StoreRecord(OpRecord::DeleteEntry {
            original_action_hash,
            ..
        }) => validate_delete_target(original_action_hash),
        FlatOp::RegisterDelete(OpDelete { action }) => {
            validate_delete_target(action.deletes_address)
        }

        // This DNA defines no link types.
        FlatOp::RegisterCreateLink { .. } | FlatOp::StoreRecord(OpRecord::CreateLink { .. }) => {
            Ok(ValidateCallbackResult::Invalid(NO_LINKS.into()))
        }
        _ => Ok(ValidateCallbackResult::Valid),
    }
}

fn validate_create(entry: &EntryTypes, author: &AgentPubKey, ts: Timestamp) -> Result<(), String> {
    let now = ts.as_micros();
    match entry {
        EntryTypes::AgentConfig(c) => check_agent_config(c, now),
        EntryTypes::AgentToken(t) => check_agent_token(t, author, now),
        EntryTypes::SealedBundle(b) => check_sealed_bundle(b, now),
        EntryTypes::TokenRevocation(r) => check_revocation(r, now),
        EntryTypes::AccessEvent(e) => check_access_event(e, now),
    }
}

fn validate_delete_target(original: ActionHash) -> ExternResult<ValidateCallbackResult> {
    let action = must_get_action(original)?;
    match action.action().entry_type() {
        Some(EntryType::App(_)) => Ok(ValidateCallbackResult::Invalid(APPEND_ONLY.into())),
        _ => Ok(ValidateCallbackResult::Valid),
    }
}

fn to_callback(r: Result<(), String>) -> ValidateCallbackResult {
    match r {
        Ok(()) => ValidateCallbackResult::Valid,
        Err(e) => ValidateCallbackResult::Invalid(e),
    }
}
